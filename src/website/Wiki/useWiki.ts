import { useEffect, useState } from 'react';
import type { LoadState, WikiManifest } from './wikiTypes';

/**
 * Fetches the wiki navigation manifest once on mount.
 *
 * @returns The manifest's {@link LoadState}: `loading`, then either `ready` with
 * the parsed {@link WikiManifest} or `error` with a message. An in-flight fetch
 * is aborted if the component unmounts first.
 */
export function useWikiManifest(): LoadState<WikiManifest> {
  const [state, setState] = useState<LoadState<WikiManifest>>({
    status: 'loading',
  });

  useEffect(() => {
    const controller = new AbortController();
    const load = async () => {
      try {
        const res = await fetch('/wiki-data/manifest.json', {
          signal: controller.signal,
        });
        if (!res.ok)
          throw new Error(`Manifest request failed (${String(res.status)}).`);
        const data = (await res.json()) as unknown;
        // The manifest is generated by scripts/build-wiki.mjs and served from our
        // own origin, so its shape is guaranteed. A cast at this trusted IO
        // boundary is the honest option; runtime validation would only re-check
        // our own build output.
        // oxlint-disable-next-line typescript/no-unsafe-type-assertion
        setState({ status: 'ready', data: data as WikiManifest });
      } catch (error: unknown) {
        if (controller.signal.aborted) return;
        setState({
          status: 'error',
          message:
            error instanceof Error ?
              error.message
            : 'Could not load the wiki index.',
        });
      }
    };
    void load();
    return () => {
      controller.abort();
    };
  }, []);

  return state;
}

/**
 * Fetches one wiki page's cleaned HTML fragment, re-fetching whenever `slug`
 * changes.
 *
 * @param slug - Page identifier; the fragment served is `/wiki-data/pages/<slug>.html`.
 * @returns The fragment's {@link LoadState}: `loading`, then `ready` with the raw
 * HTML string or `error` with a message. The previous request is aborted when
 * `slug` changes or the component unmounts.
 *
 * @remarks
 * The returned HTML is trusted, build-time-cleaned archive content (see
 * `scripts/build-wiki.mjs`). The caller injects it via `dangerouslySetInnerHTML`.
 */
export function useWikiPage(slug: string): LoadState<string> {
  const [state, setState] = useState<LoadState<string>>({ status: 'loading' });

  useEffect(() => {
    setState({ status: 'loading' });
    const controller = new AbortController();
    const load = async () => {
      try {
        const res = await fetch(
          `/wiki-data/pages/${encodeURIComponent(slug)}.html`,
          { signal: controller.signal },
        );
        if (!res.ok)
          throw new Error(
            `That page could not be found (${String(res.status)}).`,
          );
        const html = await res.text();
        setState({ status: 'ready', data: html });
      } catch (error: unknown) {
        if (controller.signal.aborted) return;
        setState({
          status: 'error',
          message:
            error instanceof Error ?
              error.message
            : 'Could not load this page.',
        });
      }
    };
    void load();
    return () => {
      controller.abort();
    };
  }, [slug]);

  return state;
}
