/** A single wiki page, as listed in the navigation manifest. */
export interface WikiPageRef {
  /** URL-safe page identifier; the file served is `/wiki-data/pages/<slug>.html`. */
  readonly slug: string;
  /** Display title, taken from the page's original heading. */
  readonly title: string;
}

/** A titled group of wiki pages in the navigation. */
export interface WikiSection {
  /** Section heading, e.g. `Features`. */
  readonly heading: string;
  /** Pages in the section, in navigation order. */
  readonly pages: readonly WikiPageRef[];
}

/**
 * The wiki navigation manifest, generated by `scripts/build-wiki.mjs` and served
 * at `/wiki-data/manifest.json`.
 */
export interface WikiManifest {
  /** Slug of the landing page shown at `/wiki`. */
  readonly home: string;
  /** The navigation, grouped into sections. */
  readonly sections: readonly WikiSection[];
}

/**
 * The lifecycle of an async fetch, as a discriminated union so the UI must
 * handle every state and can never read data that has not arrived.
 *
 * @typeParam T - The successfully-loaded value.
 */
export type LoadState<T> =
  | { readonly status: 'loading' }
  | { readonly status: 'error'; readonly message: string }
  | { readonly status: 'ready'; readonly data: T };
